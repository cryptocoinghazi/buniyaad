import { readFile, writeFile, mkdir } from "node:fs/promises";
import vm from "node:vm";
const source = await readFile("dist/app.js", "utf8");
const start = source.indexOf("  const TRANSLATIONS =");
const end = source.indexOf("  const SHARED =");
if (start < 0 || end < start)
  throw new Error("Translation dictionaries could not be extracted");
const dictionaries = vm.runInNewContext(
  source.slice(start, end) +
    ";({TRANSLATIONS,PAGE_TRANSLATIONS,TRANSLATION_ALIASES})",
  {},
  { timeout: 1000 },
);
const escape = (s) =>
  String(s).replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
const template = (await readFile("dist/index.html", "utf8")).replace(
  /(src|href)="(assets\/|styles\.css|app\.js|admin\.html)/g,
  '$1="/$2',
);
const templates = {};
for (const lang of ["en", "hi", "mr"]) {
  const {
    TRANSLATIONS: T,
    PAGE_TRANSLATIONS: P,
    TRANSLATION_ALIASES: A,
  } = dictionaries;
  const t = (k) =>
    P[lang]?.[k] ||
    T[lang]?.[k] ||
    T[lang]?.[A[k]] ||
    P.en[k] ||
    T.en[k] ||
    T.en[A[k]];
  templates[lang] = template
    .replace(
      /<([a-z][\w-]*)\b([^>]*\bdata-i18n="([^"]+)"[^>]*)>([\s\S]*?)<\/\1>/g,
      (all, tag, attrs, key) =>
        t(key) ? `<${tag}${attrs}>${escape(t(key))}</${tag}>` : all,
    )
    .replace('<html lang="en">', `<html lang="${lang}">`);
}
await mkdir("worker", { recursive: true });
await writeFile(
  "worker/templates.generated.mjs",
  `// Generated by npm run build. Do not edit.\nexport const templates = ${JSON.stringify(templates)};\n`,
);
console.log(
  "Built three server-rendered homepage templates; no deployment performed.",
);
